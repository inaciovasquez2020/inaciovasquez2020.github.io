export function getLocale(lang){return Object.hasOwn(LOCALES,lang)?lang:'en';}
export function translate(key,lang){return LOCALES[getLocale(lang)][key]??LOCALES.en[key]??key;}
export function applyLanguage(root,lang){
 const locale=getLocale(lang);
 for(const element of root.querySelectorAll('[data-i18n]')){
   element.textContent=translate(element.dataset.i18n,locale);
 }
 root.documentElement?.setAttribute('lang',locale);
 return locale;
}
const selector=typeof document!=='undefined'?document.getElementById('ui-language'):null;
if(selector){
 selector.addEventListener('change',()=>applyLanguage(document,selector.value));
 applyLanguage(document,selector.value);
}
